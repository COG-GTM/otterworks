#!/usr/bin/env python3
"""Render the local observability config into in-cluster CRs.

Sources (unchanged, still used by docker-compose):
  observability/prometheus/alerts.yml           -> PrometheusRule otterworks-alerts
  observability/prometheus/recording_rules.yml  -> PrometheusRule otterworks-recording-rules
  observability/grafana/dashboards/*.json       -> one ConfigMap per dashboard (Grafana sidecar)

The cluster is multi-tenant, so every `by (...)` aggregation also keeps
`namespace` (one series per tenant instead of all tenants summed together),
and every alert carries `affected_service` (the label admin-service's
/api/v1/admin/alerts/ingest keys incidents on) and `tenant`.

Usage:
  generate.py           # (re)write generated/
  generate.py --check   # exit 1 if generated/ is stale (CI)
"""
import json
import pathlib
import re
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
SRC = REPO / "observability"
OUT = HERE / "generated"
NAMESPACE = "monitoring"
HEADER = "# GENERATED by demo-platform/k8s/observability/generate.py -- do not edit.\n"

# Alerts that are not per-service: name the owner explicitly so admin-service
# can still open an incident against something.
SERVICE_OVERRIDES = {
    "WebSocketConnectionsHigh": "collab-service",
    "CRDTSyncDelayHigh": "collab-service",
}

# The shared Prometheus also scrapes platform targets (kube-prometheus-stack has its
# own TargetDown for those); OtterWorks availability alerts cover app namespaces only.
EXPR_OVERRIDES = {
    "ServiceDown": 'up{namespace=~"otterworks(-.*)?"} == 0',
}

BY_RE = re.compile(r"\bby\s*\(([^)]*)\)")


class Literal(str):
    pass


def _literal(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")


yaml.SafeDumper.add_representer(Literal, _literal)


def tenant_aware(expr: str, keep_job: bool = False) -> str:
    """Keep `namespace` (and, for alerts labelled from it, `job`) through every by()."""
    def repl(m):
        labels = [l.strip() for l in m.group(1).split(",") if l.strip()]
        if keep_job and "job" not in labels:
            labels.insert(0, "job")
        if "namespace" not in labels:
            labels.insert(0, "namespace")
        return "by (" + ", ".join(labels) + ")"

    return " ".join(BY_RE.sub(repl, expr).split())


def port_rules(path: pathlib.Path, alerting: bool):
    groups = yaml.safe_load(path.read_text())["groups"]
    for group in groups:
        for rule in group["rules"]:
            if alerting and rule.get("alert") in EXPR_OVERRIDES:
                rule["expr"] = EXPR_OVERRIDES[rule["alert"]]
            keep_job = alerting and "alert" in rule and rule["alert"] not in SERVICE_OVERRIDES
            rule["expr"] = tenant_aware(str(rule["expr"]), keep_job)
            if alerting and "alert" in rule:
                labels = rule.setdefault("labels", {})
                labels.setdefault(
                    "affected_service",
                    SERVICE_OVERRIDES.get(rule["alert"], "{{ $labels.job }}"),
                )
                labels.setdefault("tenant", "{{ $labels.namespace }}")
    return groups


def prometheus_rule(name, groups):
    return {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {
            "name": name,
            "namespace": NAMESPACE,
            "labels": {"app.kubernetes.io/part-of": "otterworks-observability"},
        },
        "spec": {"groups": groups},
    }


def dashboards():
    docs = []
    for f in sorted((SRC / "grafana" / "dashboards").glob("*.json")):
        json.loads(f.read_text())  # fail loudly on invalid JSON
        docs.append({
            "apiVersion": "v1",
            "kind": "ConfigMap",
            "metadata": {
                "name": f"grafana-dashboard-{f.stem}",
                "namespace": NAMESPACE,
                "labels": {
                    "grafana_dashboard": "1",
                    "app.kubernetes.io/part-of": "otterworks-observability",
                },
                "annotations": {"grafana_folder": "OtterWorks"},
            },
            "data": {f.name: Literal(f.read_text().rstrip("\n") + "\n")},
        })
    return docs


def render():
    rules = [
        prometheus_rule("otterworks-alerts", port_rules(SRC / "prometheus" / "alerts.yml", True)),
        prometheus_rule("otterworks-recording-rules",
                        port_rules(SRC / "prometheus" / "recording_rules.yml", False)),
    ]
    dump = lambda docs: HEADER + yaml.safe_dump_all(docs, sort_keys=False, width=1000)
    return {"prometheus-rules.yaml": dump(rules), "grafana-dashboards.yaml": dump(dashboards())}


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for name, content in render().items():
        target = OUT / name
        if check:
            if not target.exists() or target.read_text() != content:
                stale.append(str(target.relative_to(REPO)))
        else:
            OUT.mkdir(exist_ok=True)
            target.write_text(content)
            print(f"wrote {target.relative_to(REPO)}")
    if stale:
        print("stale (run demo-platform/k8s/observability/generate.py):", *stale, sep="\n  ")
        sys.exit(1)


if __name__ == "__main__":
    main()
